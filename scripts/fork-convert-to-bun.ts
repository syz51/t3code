// @effect-diagnostics nodeBuiltinImport:off - runs on upstream's pnpm files before any install exists.
// Fork-only: converts upstream's pnpm setup to bun. Run with `bun scripts/fork-convert-to-bun.ts`
// after each upstream sync; docs/operations/fork.md explains when.
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodeOS from "node:os";
import * as NodePath from "node:path";

for (const file of ["pnpm-lock.yaml", "pnpm-workspace.yaml"]) {
  if (!NodeFS.existsSync(file)) {
    throw new Error(`${file} is missing. Restore upstream's package.json and pnpm files first.`);
  }
}

// Reads the entries of a top-level list or map in pnpm-workspace.yaml.
const workspaceYaml = NodeFS.readFileSync("pnpm-workspace.yaml", "utf8").split("\n");
const section = (name: string) => {
  const lines: Array<string> = [];
  let inSection = false;
  for (const line of workspaceYaml) {
    if (/^\S/.test(line)) inSection = line.startsWith(`${name}:`);
    else if (inSection && line.trim() !== "" && !line.trim().startsWith("#")) {
      lines.push(line.trim());
    }
  }
  return lines;
};
// The package name in an entry such as `- "@scope/name@1.0.0"` or `"name@file:x.tgz": true`.
const packageName = (entry: string) => entry.match(/^(?:- )?"?(@?[^@":\s]+)/)![1]!;

// pnpm's allowBuilds lists every package with an install script; only `true` may run it.
const trusted = section("allowBuilds")
  .filter((entry) => /:\s*true$/.test(entry))
  .map(packageName);

// Bun has no workspace file; its install settings live in bunfig.toml.
const tomlList = (values: Array<string>) =>
  `[\n${values.map((value) => `  ${JSON.stringify(value)},\n`).join("")}]`;
const releaseAgeExcludes = [...new Set(section("minimumReleaseAgeExclude").map(packageName))];
NodeFS.writeFileSync(
  "bunfig.toml",
  `# Generated by scripts/fork-convert-to-bun.ts from upstream's pnpm-workspace.yaml.
[install]
linker = "isolated"
# @cursor/sdk finds its platform package (sandbox helper, rg, tree-sitter) by
# walking up from the entry script for node_modules/@cursor/sdk-<platform>-<arch>.
publicHoistPattern = ${tomlList(section("publicHoistPattern").map((entry) => entry.replace(/^- "?|"$/g, "")))}
# pnpm's default: resolve only versions published at least a day ago. Bun exempts
# every version of an excluded package; pnpm exempts only the listed version.
minimumReleaseAge = 86400
minimumReleaseAgeExcludes = ${tomlList(releaseAgeExcludes.toSorted())}
`,
);

const install = () => {
  const result = NodeChildProcess.spawnSync(
    "bun",
    ["install", "--lockfile-only", "--ignore-scripts"],
    { encoding: "utf8" },
  );
  const output = `${result.stdout}${result.stderr}`;
  if (result.status !== 0) throw new Error(`bun install failed:\n${output}`);
  return output;
};

NodeFS.rmSync("bun.lock", { force: true });
// With no bun.lock, bun migrates pnpm-lock.yaml and copies pnpm-workspace.yaml into package.json.
const migration = install();

const pkg = JSON.parse(NodeFS.readFileSync("package.json", "utf8"));
pkg.packageManager = `bun@${process.versions.bun}`;
// `prepare` runs Vite+ on every install.
delete pkg.scripts.prepare;
// Bun's --filter skips the apps whose typecheck is only a Vite+ task in their vite.config.ts.
pkg.scripts["typecheck:bun"] = [
  "bun --bun run --filter '*' typecheck",
  "bun --bun run --cwd apps/web effect-tsgo tsrs --noEmit",
  "bun --bun run --cwd apps/desktop effect-tsgo tsrs --noEmit",
  "bun --bun run --cwd apps/marketing astro check",
].join(" && ");
// Bun cannot remove a dependency edge with "-"; those packages install instead.
for (const [name, spec] of Object.entries(pkg.overrides ?? {})) {
  if (spec === "-") delete pkg.overrides[name];
}
// Bun rejects catalog: specs in packageExtensions.
for (const extension of Object.values(pkg.packageExtensions ?? {}) as Array<{
  dependencies?: Record<string, string>;
}>) {
  for (const [name, spec] of Object.entries(extension.dependencies ?? {})) {
    if (spec === "catalog:") extension.dependencies![name] = pkg.workspaces.catalog[name];
  }
}
// Bun keys a patched tarball dependency by its tarball path, not its manifest version.
// Any other "no longer applies" warning is real version drift and fails below.
for (const [, patch, name, version] of migration.matchAll(
  /warn: (\S+) no longer applies \((\S+) is now (\S+\.tgz)\)/g,
)) {
  const key = Object.keys(pkg.patchedDependencies).find(
    (candidate) => pkg.patchedDependencies[candidate] === patch,
  );
  if (key === undefined) continue;
  delete pkg.patchedDependencies[key];
  pkg.patchedDependencies[`${name}@${version}`] = patch;
}
pkg.trustedDependencies = trusted.toSorted();
NodeFS.writeFileSync("package.json", `${JSON.stringify(pkg, null, 2)}\n`);

const warnings = install()
  .split("\n")
  .filter((line) => line.startsWith("warn:"));
if (warnings.length > 0) throw new Error(`bun still warns:\n${warnings.join("\n")}`);

// The isolated linker reads a workspace's file: tarball from the repo root, so an install with a
// cold cache fails with ENOENT. Bun keeps a root-relative path once the lockfile has it.
// Patched tarballs install by another route and keep the path their patch key names.
let lock = NodeFS.readFileSync("bun.lock", "utf8");
for (const dir of (pkg.workspaces.packages as Array<string>).flatMap((glob) =>
  NodeFS.globSync(glob),
)) {
  const manifest = NodePath.join(dir, "package.json");
  if (!NodeFS.existsSync(manifest)) continue;
  const { dependencies, devDependencies } = JSON.parse(NodeFS.readFileSync(manifest, "utf8"));
  for (const [name, spec] of Object.entries({ ...dependencies, ...devDependencies })) {
    const tarball = (spec as string).match(/^file:(.+\.tgz)$/)?.[1];
    if (tarball === undefined || `${name}@${tarball}` in (pkg.patchedDependencies ?? {})) continue;
    lock = lock.replaceAll(`["${name}@${tarball}"`, `["${name}@${NodePath.join(dir, tarball)}"`);
  }
}
NodeFS.writeFileSync("bun.lock", lock);
install();

// Format as `vp fmt` does (oxfmt with sortPackageJson), with the lockfile's oxfmt.
const oxfmtVersion = NodeFS.readFileSync("bun.lock", "utf8").match(
  /"oxfmt": \["oxfmt@([^"]+)"/,
)![1];
const formatConfig = NodePath.join(
  NodeFS.mkdtempSync(NodePath.join(NodeOS.tmpdir(), "fork-convert-")),
  ".oxfmtrc.json",
);
NodeFS.writeFileSync(formatConfig, JSON.stringify({ sortPackageJson: {} }));
const format = NodeChildProcess.spawnSync(
  "bunx",
  [
    `oxfmt@${oxfmtVersion}`,
    "-c",
    formatConfig,
    "--ignore-path=/dev/null",
    "package.json",
    "bunfig.toml",
  ],
  { encoding: "utf8" },
);
NodeFS.rmSync(NodePath.dirname(formatConfig), { recursive: true });
if (format.status !== 0) throw new Error(`oxfmt failed:\n${format.stdout}${format.stderr}`);

for (const file of ["pnpm-lock.yaml", "pnpm-workspace.yaml", ".pnpmfile.cjs"]) {
  NodeFS.rmSync(file, { force: true });
}
process.stdout.write("Converted to bun. Run `bun install`, then review and commit the result.\n");
